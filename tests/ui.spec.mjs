import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const base = process.env.NOFY_UI_URL || 'http://127.0.0.1:4318';
const output = 'work/design/verified';
await mkdir(output, { recursive: true });
const reports = [];
try {
  for (let run = 1; run <= 3; run++) {
    const context = await browser.newContext({ viewport: { width: 1120, height: 820 }, colorScheme: 'light' });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('console', msg => { if (msg.type() === 'error' && !msg.text().includes('favicon.ico')) errors.push(msg.text()); });
    const capture = async (options) => { await page.evaluate(async () => { window.scrollTo(0, 0); await Promise.all(document.getAnimations().filter(a => a.effect?.getTiming().iterations !== Infinity).map(a => a.finished.catch(() => {}))); }); await page.screenshot(options); };
    const button = name => page.getByRole('button', { name, exact: true });
    await page.goto(base);
    await page.waitForFunction(() => document.querySelector('#install-path')?.disabled === false);
    await button('检测安装').click();
    await page.getByText('检测通过', { exact: true }).waitFor();
    if (run === 1) await capture({ path: `${output}/detected.png`, fullPage: true });
    await button('查看检测详情').click();
    await page.getByText('EXE 与 ASAR 一致，翻译加载器唯一匹配').waitFor();
    await button('查看检测详情').click();
    await page.locator('#install-path').fill('C:\\invalid');
    assert.equal(await button('创建修复副本').count(), 0, 'editing invalidates inspection');
    await button('检测安装').click();
    await page.getByText('操作未完成', { exact: true }).waitFor();
    assert.equal(await page.locator('#install-path').inputValue(), 'C:\\invalid', 'failure preserves input');
    if (run === 1) await capture({ path: `${output}/error.png`, fullPage: true });
    await button('选择安装目录').click();
    await page.waitForFunction(() => document.querySelector('#install-path').value.includes('Programs'));
    await button('检测安装').click();
    await button('创建修复副本').waitFor();
    await button('创建修复副本').click();
    await button('启动副本').waitFor();
    assert.equal(await button('启动 Codex').isVisible(), true, 'primary action advances to launch');
    assert.equal(await page.evaluate(() => window.uiTest.calls.filter(x => x === 'repair').length), 1);
    if (run === 1) await capture({ path: `${output}/created.png`, fullPage: true });
    await button('启动副本').click();
    await page.getByText(/已发出启动请求/).waitFor();
    await page.reload();
    await button('启动副本').waitFor();
    await page.waitForFunction(() => document.querySelector('#install-path')?.disabled === false);
    await button('恢复').click();
    await page.getByText('已恢复', { exact: true }).waitFor();
    assert.equal(await button('启动副本').count(), 0);
    await page.reload();
    await page.getByText('已恢复', { exact: true }).waitFor();
    await page.locator('.search-entry').click();
    await page.getByRole('dialog', { name: '搜索工具' }).waitFor();
    await page.getByPlaceholder('搜索工具或设置…').fill('不存在');
    await page.getByText('没有找到匹配的工具。').waitFor();
    await page.getByPlaceholder('搜索工具或设置…').fill('设置');
    await page.keyboard.press('Enter');
    await page.getByRole('heading', { name: '设置', exact: true }).waitFor();
    await button('深色').click();
    await page.waitForFunction(() => document.documentElement.classList.contains('dark'));
    if (run === 1) await capture({ path: `${output}/settings-dark.png`, fullPage: true });
    await page.reload();
    assert.equal(await page.evaluate(() => localStorage.getItem('nofy-helper.theme')), 'dark');
    await page.waitForFunction(() => document.documentElement.classList.contains('dark'));
    await button('设置').click();
    await page.evaluate(() => { window.savedStorageSetter = Storage.prototype.setItem; Storage.prototype.setItem = () => { throw new Error('disk full'); }; });
    await button('浅色').click();
    await page.getByText('设置未保存', { exact: true }).waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.classList.contains('dark')), true, 'failed theme persistence keeps previous theme');
    await page.evaluate(() => { Storage.prototype.setItem = window.savedStorageSetter; });
    await button('浅色').click();
    await button('Codex 中文修复').click();
    await button('切换侧栏').click();
    await page.locator('[data-slot="sidebar"][data-state="collapsed"]').waitFor();
    await button('切换侧栏').click();
    await page.keyboard.press('Control+k');
    await page.getByRole('dialog', { name: '搜索工具' }).waitFor();
    await page.keyboard.press('Escape');
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    await page.setViewportSize({ width: 850, height: 680 });
    await page.locator('#install-path').fill('C:\\Users\\非常长的中文名称\\'.repeat(12));
    await button('检测安装').click();
    await button('创建修复副本').waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'small window has no horizontal overflow');
    if (run === 1) await capture({ path: `${output}/small-window.png`, fullPage: true });
    await page.setViewportSize({ width: 1120, height: 820 });
    await page.evaluate(() => { document.documentElement.style.zoom = '2'; });
    await button('创建修复副本').scrollIntoViewIfNeeded();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, '200% zoom has no horizontal overflow');
    if (run === 1) await capture({ path: `${output}/zoom-200.png`, fullPage: true });
    await page.evaluate(() => { document.documentElement.style.zoom = ''; });
    await page.emulateMedia({ reducedMotion: 'reduce' });
    assert.equal(await page.locator('.tool-page').evaluate(el => getComputedStyle(el).animationName), 'none');
    await page.goto(`${base}?state=mac`);
    await page.getByText('当前系统暂不支持此工具').waitFor();
    assert.equal(await button('检测安装').isDisabled(), true);
    await button('设置').click();
    await page.getByRole('heading', { name: '设置', exact: true }).waitFor();
    await button('Codex 中文修复').click();
    if (run === 1) await capture({ path: `${output}/mac.png`, fullPage: true });
    assert.deepEqual(errors, [], 'no renderer or console errors');
    reports.push({ run, passed: true, checks: ['detection', 'inspection invalidation', 'error preserves input', 'repair', 'launch request', 'restore and reload', 'search and keyboard', 'theme persistence', 'failed storage', 'sidebar', '850px long path', '200% zoom', 'reduced motion', 'mac capability gating'], errors });
    await context.close();
    console.log(`UI flow ${run}/3 passed`);
  }
  await writeFile(`${output}/checks.json`, JSON.stringify(reports, null, 2));
} finally { await browser.close(); }
